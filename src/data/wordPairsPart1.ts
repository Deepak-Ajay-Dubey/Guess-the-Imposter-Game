import type { CuratedCategoryId } from '../types/game';

export interface CuratedWordEntry {
  category: CuratedCategoryId;
  wordA: string;
  wordB: string;
}

function makeCategoryPairs(
  category: CuratedCategoryId,
  pairs: readonly (readonly [string, string])[]
): CuratedWordEntry[] {
  return pairs.map(([wordA, wordB]) => ({ category, wordA, wordB }));
}

